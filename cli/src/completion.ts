/**
 * `scmjs completion bash|zsh|fish`: a completion script for the shell, generated from the command tree itself, so
 * every noun, verb and option is in it without a list to keep. Arguments complete as files, which they mostly are.
 *
 *   eval "$(scmjs completion bash)"                          # ~/.bashrc
 *   scmjs completion zsh > ~/.zsh/completions/_scmjs         # a folder on $fpath
 *   scmjs completion fish > ~/.config/fish/completions/scmjs.fish
 */
import type { Command } from "commander";

export const SHELLS = ["bash", "zsh", "fish"] as const;
export type Shell = (typeof SHELLS)[number];

interface Node { name: string; description: string; options: { flag: string; description: string }[]; children: Node[] }

/** The tree commander holds, without the hidden commands and the implicit help. */
export function commandTree(cmd: Command): Node {
  return {
    name: cmd.name(),
    description: cmd.description(),
    options: cmd.options.filter((o) => !o.hidden).flatMap((o) => [o.long, o.short].filter((f): f is string => !!f).map((flag) => ({ flag, description: o.description }))),
    children: cmd.commands.filter((c) => !(c as unknown as { _hidden?: boolean })._hidden && c.name() !== "help").map(commandTree),
  };
}

export function completionScript(program: Command, shell: Shell): string {
  const tree = commandTree(program);
  return { bash: bash(tree), zsh: zsh(tree), fish: fish(tree) }[shell];
}

const sq = (s: string) => `'${s.replace(/'/g, "'\\''")}'`;
const words = (n: Node) => [...n.children.map((c) => c.name), ...n.options.map((o) => o.flag)].join(" ");

/** Every command with the words that lead to it, the root first. */
function paths(n: Node, prefix: string[] = []): { path: string[]; node: Node }[] {
  return [{ path: prefix, node: n }, ...n.children.flatMap((c) => paths(c, [...prefix, c.name]))];
}

function bash(root: Node): string {
  // Walk the typed words down the tree; what the current node offers is the completion, else files.
  const cases = paths(root).map(({ path, node }) => `    ${sq(path.join(" ") || "")}) words=${sq(words(node))} ;;`).join("\n");
  return `# bash completion for ${root.name}, generated by \`${root.name} completion bash\`
_${root.name}() {
  local cur path="" i words
  cur="\${COMP_WORDS[COMP_CWORD]}"
  for ((i = 1; i < COMP_CWORD; i++)); do
    case "\${COMP_WORDS[i]}" in -*) ;; *) path="\${path:+$path }\${COMP_WORDS[i]}" ;; esac
  done
  case "$path" in
${cases}
    *) words="" ;;
  esac
  if [[ -n "$words" && ( -z "$cur" || "$cur" == -* || "$path" != *" "* || "$words" == *"$cur"* ) ]]; then
    COMPREPLY=( $(compgen -W "$words" -- "$cur") )
    [[ \${#COMPREPLY[@]} -gt 0 ]] && return 0
  fi
  COMPREPLY=( $(compgen -f -- "$cur") )
}
complete -o filenames -F _${root.name} ${root.name}
`;
}

function zsh(root: Node): string {
  const fn = (path: string[]) => `_${root.name}${path.map((p) => `_${p}`).join("")}`;
  const functions = paths(root).map(({ path, node }) => {
    const opts = node.options.map((o) => `    ${sq(`${o.flag}[${o.description.replace(/[[\]]/g, "")}]`)}`).join(" \\\n");
    if (node.children.length === 0) {
      return `${fn(path)}() {\n  _arguments -s \\\n${opts ? `${opts} \\\n` : ""}    '*:file:_files'\n}`;
    }
    const subs = node.children.map((c) => sq(`${c.name}:${c.description.replace(/:/g, "\\:")}`)).join(" ");
    const dispatch = node.children.map((c) => `        ${c.name}) ${fn([...path, c.name])} ;;`).join("\n");
    return `${fn(path)}() {
  local -a subs
  subs=(${subs})
  _arguments -C \\
${opts ? `${opts} \\\n` : ""}    '1:command:->command' \\
    '*::arg:->args'
  case $state in
    command) _describe 'command' subs ;;
    args)
      case $words[1] in
${dispatch}
      esac ;;
  esac
}`;
  }).join("\n\n");
  return `#compdef ${root.name}
# zsh completion for ${root.name}, generated by \`${root.name} completion zsh\`

${functions}

${fn([])} "$@"
`;
}

function fish(root: Node): string {
  const lines: string[] = [`# fish completion for ${root.name}, generated by \`${root.name} completion fish\``];
  const seen = (path: string[]) => (path.length === 0 ? "__fish_use_subcommand" : path.map((p) => `__fish_seen_subcommand_from ${p}`).join("; and "));
  for (const { path, node } of paths(root)) {
    const notDeeper = node.children.length > 0 ? `; and not __fish_seen_subcommand_from ${node.children.map((c) => c.name).join(" ")}` : "";
    const cond = path.length === 0 ? seen(path) : `${seen(path)}${notDeeper}`;
    for (const c of node.children) lines.push(`complete -c ${root.name} -n ${sq(cond)} -a ${c.name} -d ${sq(c.description)}`);
    for (const o of node.options) {
      const long = o.flag.startsWith("--") ? `-l ${o.flag.slice(2)}` : `-s ${o.flag.slice(1)}`;
      lines.push(`complete -c ${root.name} -n ${sq(cond)} ${long} -d ${sq(o.description)}`);
    }
  }
  return lines.join("\n") + "\n";
}
