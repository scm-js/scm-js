// Builds `@scm-js/core` (core/, docs/core.md): the editor's map code as a library, from the same source the editor
// and the `scmjs` command are built from. Two files: core/dist/index.mjs, one ES module with everything behind
// core/src/index.ts compiled in (mopaq stays a dependency), and core/dist/index.d.ts, its declarations in one file.
// The version is the editor's (package.json), written into core/package.json too.
//   npm run build:core                  then: node -e 'import("./core/dist/index.mjs").then(console.log)'
import { generateDtsBundle } from "dts-bundle-generator";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { build } from "vite";
import { importsIn } from "./build-plugin-types.mjs";
import { coreNotices } from "./lib/notices.mjs";

const version = JSON.parse(readFileSync("package.json", "utf8")).version;
const corePackage = JSON.parse(readFileSync("core/package.json", "utf8"));
if (corePackage.version !== version) {
  corePackage.version = version;
  writeFileSync("core/package.json", JSON.stringify(corePackage, null, 2) + "\n");
}

/** The packages a library may import at run time: its dependencies, and nothing else. */
const EXTERNAL = Object.keys(corePackage.dependencies ?? {});
const KO_CATALOGUE = resolve("src/i18n/ko.json");

await build({
  configFile: false,
  logLevel: "warn",
  publicDir: false,
  plugins: [
    {
      // The Korean catalogue is a third of the editor's words; the library's own text (a warning, an issue) is
      // English, and nothing in it can switch language, so the catalogue is left out.
      name: "scmjs-core-no-catalogue",
      enforce: "pre",
      async resolveId(source, importer) {
        if (!source.endsWith("ko.json") || !importer) return null;
        const resolved = await this.resolve(source, importer, { skipSelf: true });
        return resolved && resolve(resolved.id) === KO_CATALOGUE ? "\0scmjs-core-empty-catalogue" : null;
      },
      load(id) {
        return id === "\0scmjs-core-empty-catalogue" ? "export default {};" : null;
      },
    },
    {
      // The packages the bundle holds, from its modules' paths; a file only when there is one.
      name: "scmjs-core-notices",
      generateBundle(_, bundle) {
        const names = new Set();
        for (const chunk of Object.values(bundle)) {
          if (chunk.type !== "chunk") continue;
          for (const id of chunk.moduleIds) {
            const m = /node_modules\/((?:@[^/]+\/)?[^/]+)\/(?!.*node_modules\/)/.exec(id.replace(/\\/g, "/"));
            if (m) names.add(m[1]);
          }
        }
        if (names.size > 0) this.emitFile({ type: "asset", fileName: "THIRD-PARTY-NOTICES.txt", source: coreNotices(".", [...names].sort(), version) });
      },
    },
  ],
  ssr: { noExternal: true, external: EXTERNAL, target: "node" },
  build: {
    ssr: "core/src/index.ts",
    outDir: "core/dist",
    emptyOutDir: true,
    target: "node22",
    minify: false,
    reportCompressedSize: false,
    rollupOptions: { external: EXTERNAL, output: { entryFileNames: "index.mjs", format: "es", codeSplitting: false } },
  },
});

// The declarations: one file, with the editor's own modules inlined and only the dependencies imported.
const [dts] = generateDtsBundle(
  [{ filePath: resolve("core/src/index.ts"), output: { noBanner: true, sortNodes: false } }],
  { preferredConfigPath: resolve("tsconfig.core.json") },
);
const stray = importsIn(dts).filter((name) => !EXTERNAL.includes(name));
if (stray.length > 0) throw new Error(`core/dist/index.d.ts imports ${stray.join(", ")}; a type it names has to be in the file or in a dependency.`);
for (const forbidden of ["jotai", "react"]) {
  if (new RegExp(`["']${forbidden}(/|["'])`).test(dts)) throw new Error(`core/dist/index.d.ts names ${forbidden}; the library's types must not reach the UI.`);
}
const banner = [
  "/**",
  ` * @scm-js/core ${version} — StarCraft maps as the scmJS editor reads and writes them.`,
  " * Generated by `npm run build:core` in github.com/scm-js/scm-js from core/src/index.ts; the guide is docs/core.md.",
  " */",
  "",
].join("\n");
writeFileSync("core/dist/index.d.ts", banner + dts);

const js = readFileSync("core/dist/index.mjs");
if (!process.argv.includes("--quiet")) console.log(`core/dist/index.mjs (${Math.round(js.length / 1024)} KB) + index.d.ts (${Math.round(dts.length / 1024)} KB): @scm-js/core ${version}`);
