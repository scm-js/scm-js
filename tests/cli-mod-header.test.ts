/**
 * `scmjs mod header`: a mod's ids by name as C++ for a BWAPI bot and as JSON. A mod made by the test — every table,
 * a renamed SCV and Command Center, a wider units.datex named by unitnames.tbl, a duplicate name, "None" and
 * "Reserved" rows — gives the expected header lines and JSON; the identifier rules; `--bot` writes the mod into a
 * bot's scmbot.json and keeps the rest.
 */
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { emptyDat, encodeDat } from "../src/formats/dat/table";
import { encodeTblFile } from "../src/formats/dat/tblFile";
import { headerEntries, identifierOf, unusedName, withMod, writeModHeader } from "../cli/src/mod/header";
import { sourceHash } from "../cli/src/mod/hash";
import { openMod } from "../cli/src/mod/open";
import { CliError } from "../cli/src/ui";

const dir = mkdtempSync(join(tmpdir(), "scmjs-mod-header-"));

/** A mod folder: 230 units named in unitnames.tbl, weapons, upgrades and techs labelled in stat_txt.tbl. */
function testMod(): string {
  const folder = join(dir, `Test Mod ${Math.random().toString(36).slice(2, 6)}`);
  // (the units' own entries first, empty: a unit without a unitnames.tbl name falls back to stat_txt.tbl's)
  const stat = [...Array.from({ length: 230 }, () => "\0"), "Gauss Rifle\0", "Stim Packs\0", "U-238 Shells\0", "None\0"];
  const label = (s: string) => stat.indexOf(`${s}\0`) + 1;
  const units = emptyDat("units", 230, "expanded");
  const unitNames = Array.from({ length: 230 }, () => "\0");
  unitNames[0] = "Terran Marine\0";
  unitNames[7] = "Terran Mason\0";
  unitNames[106] = "Terran Ministry\0";
  unitNames[228] = "Reserved\0";
  unitNames[229] = "Terran Quarry\0";
  const weapons = emptyDat("weapons");
  weapons.columns.label[0] = label("Gauss Rifle");
  weapons.columns.label[1] = label("Gauss Rifle");
  weapons.columns.label[130] = label("None");
  const upgrades = emptyDat("upgrades");
  upgrades.columns.label[16] = label("U-238 Shells");
  const techs = emptyDat("techdata");
  techs.columns.label[0] = label("Stim Packs");
  const files: [string, Uint8Array][] = [
    ["arr/units.dat", encodeDat(units)], ["arr/weapons.dat", encodeDat(weapons)], ["arr/upgrades.dat", encodeDat(upgrades)],
    ["arr/techdata.dat", encodeDat(techs)],
    ["rez/unitnames.tbl", encodeTblFile({ strings: unitNames, encoding: "windows-1252" })],
    ["rez/stat_txt.tbl", encodeTblFile({ strings: stat, encoding: "windows-1252" })],
  ];
  for (const [name, bytes] of files) {
    const path = join(folder, name);
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, bytes);
  }
  return folder;
}

describe("identifiers", () => {
  it("makes a name an identifier", () => {
    expect(identifierOf("Terran Mason")).toBe("Terran_Mason");
    expect(identifierOf("U-238 Shells")).toBe("U_238_Shells");
    expect(identifierOf("  Siege Tank (Tank Mode)  ")).toBe("Siege_Tank_Tank_Mode");
    expect(identifierOf("1st Battalion")).toBe("_1st_Battalion");
    expect(identifierOf("new")).toBe("_new");
    expect(identifierOf("ERROR")).toBe("_ERROR");
    expect(identifierOf("미네랄")).toBe("");
  });

  it("skips the game's placeholders", () => {
    for (const n of ["", "  ", "None", "none", "Reserved", "Unused", "Unused (Zerg)", "*"]) expect(unusedName(n), n).toBe(true);
    for (const n of ["Unused Terran Bldg", "Nonexistent", "Terran Mason"]) expect(unusedName(n), n).toBe(false);
  });

  it("keeps the first of a name and suffixes the rest with their ids; a name with no letters left is its kind and id", () => {
    expect(headerEntries(["Gauss Rifle", "Gauss Rifle", "", "None", "미네랄", "Gauss Rifle"], "Weapon")).toEqual([
      { id: 0, name: "Gauss Rifle", identifier: "Gauss_Rifle" },
      { id: 1, name: "Gauss Rifle", identifier: "Gauss_Rifle_1" },
      { id: 4, name: "미네랄", identifier: "Weapon_4" },
      { id: 5, name: "Gauss Rifle", identifier: "Gauss_Rifle_5" },
    ]);
  });
});

describe("scmjs mod header", () => {
  it("writes the header and the ids from the mod's names, with its hash", async () => {
    const folder = testMod();
    const out = join(dir, "out");
    const source = await openMod(folder, null);
    const r = await writeModHeader(source, null, { out, date: "2026-11-08" });
    const hash = (await sourceHash(await openMod(folder, null))).hash;
    expect(r.namespace).toMatch(/^Test_Mod_[a-z0-9]+$/);
    expect(r.mod).toEqual({ name: source.name, hash });
    expect(r.counts).toEqual({ units: 4, weapons: 2, upgrades: 1, techs: 1 });
    const h = readFileSync(r.files.header, "utf8");
    expect(h).toContain(`// Generated by \`scmjs mod header\` from ${source.name} (hash ${hash}) on 2026-11-08. Do not edit: run it again.`);
    expect(h).toContain("#pragma once\n#include <BWAPI.h>");
    expect(h).toContain(`namespace ${r.namespace}\n{`);
    expect(h).toContain(`  inline constexpr const char *MOD_HASH = "${hash}";`);
    expect(h).toContain("    inline const BWAPI::UnitType Terran_Mason(7);  // Terran Mason");
    expect(h).toContain("    inline const BWAPI::UnitType Terran_Quarry(229);  // Terran Quarry");
    expect(h).toContain("    inline const BWAPI::WeaponType Gauss_Rifle_1(1);  // Gauss Rifle");
    expect(h).toContain("    inline const BWAPI::UpgradeType U_238_Shells(16);  // U-238 Shells");
    expect(h).toContain("    inline const BWAPI::TechType Stim_Packs(0);  // Stim Packs");
    expect(h).toContain("    namespace Units\n    {\n      constexpr int Terran_Marine = 0;\n      constexpr int Terran_Mason = 7;");
    expect(h).not.toMatch(/Reserved|None\b/);
    const ids = JSON.parse(readFileSync(r.files.ids, "utf8"));
    expect(ids.mod).toEqual({ name: source.name, hash });
    expect(ids.units).toEqual([
      { id: 0, name: "Terran Marine", identifier: "Terran_Marine" }, { id: 7, name: "Terran Mason", identifier: "Terran_Mason" },
      { id: 106, name: "Terran Ministry", identifier: "Terran_Ministry" }, { id: 229, name: "Terran Quarry", identifier: "Terran_Quarry" },
    ]);
    expect(ids.weapons.map((w: { identifier: string }) => w.identifier)).toEqual(["Gauss_Rifle", "Gauss_Rifle_1"]);
  });

  it("fills empty labels from the mod's rez\\stat.txt and takes its own name lists over the labels", async () => {
    const folder = testMod();
    const weapons = emptyDat("weapons");
    weapons.columns.label[0] = 300;
    weapons.columns.label[1] = 231;
    writeFileSync(join(folder, "arr/weapons.dat"), encodeDat(weapons));
    // (PyTBL text: entry 300 is the weapon's name; entry 231 is the table's own, which stands)
    writeFileSync(join(folder, "rez/stat.txt"), Array.from({ length: 300 }, (_, i) => (i === 299 ? "Fusion Cutter<0>" : i === 230 ? "Not This<0>" : "<0>")).join("\n") + "\n");
    const techs = Array.from({ length: 44 }, (_, i) => (i === 0 ? "Stim Packs (Maverick)" : i === 1 ? "Extended Tech #1" : "None"));
    writeFileSync(join(folder, "arr/techdata.txt"), techs.join("\r\n"));
    const r = await writeModHeader(await openMod(folder, null), null, { out: join(dir, "lists") });
    const ids = JSON.parse(readFileSync(r.files.ids, "utf8"));
    expect(ids.weapons).toEqual([{ id: 0, name: "Fusion Cutter", identifier: "Fusion_Cutter" }, { id: 1, name: "Gauss Rifle", identifier: "Gauss_Rifle" }]);
    expect(ids.techs).toEqual([{ id: 0, name: "Stim Packs (Maverick)", identifier: "Stim_Packs_Maverick" }]);
    expect(r.lists).toEqual(["arr\\techdata.txt"]);
  });

  it("takes --namespace for the namespace and the files' name, and refuses one that is not an identifier", async () => {
    const source = await openMod(testMod(), null);
    const r = await writeModHeader(source, null, { out: join(dir, "ns"), namespace: "Cosmo" });
    expect(r.files.header).toMatch(/Cosmo\.h$/);
    expect(r.files.ids).toMatch(/Cosmo\.ids\.json$/);
    await expect(writeModHeader(source, null, { out: join(dir, "ns"), namespace: "my mod" })).rejects.toBeInstanceOf(CliError);
  });

  it("with --bot, writes into the bot's folder and gives its scmbot.json the mod, the rest kept", async () => {
    const source = await openMod(testMod(), null);
    const bot = join(dir, "bot");
    mkdirSync(bot, { recursive: true });
    const before = { key: "modbot", name: "Mod Bot", license: "LICENSE", sources: ["src/**/*.cpp"], std: "c++17", botMB: 256 };
    writeFileSync(join(bot, "scmbot.json"), JSON.stringify(before, null, 2) + "\n");
    const r = await writeModHeader(source, null, { out: bot, bot: true });
    const after = JSON.parse(readFileSync(join(bot, "scmbot.json"), "utf8"));
    expect(Object.keys(after)).toEqual([...Object.keys(before), "mod"]);
    expect(after).toEqual({ ...before, mod: { name: source.name, hash: r.mod.hash } });
    expect(r.files.scmbot).toBe(join(bot, "scmbot.json"));
  });

  it("refuses --bot for a folder with no scmbot.json", async () => {
    const source = await openMod(testMod(), null);
    const e = await writeModHeader(source, null, { out: join(dir, "nobot"), bot: true }).catch((x) => x);
    expect(e).toBeInstanceOf(CliError);
    expect(e.message).toMatch(/has no scmbot\.json/);
  });

  it("keeps the place of a mod scmbot.json had, and writes the link", () => {
    const text = JSON.stringify({ key: "a", mod: { name: "Old", hash: "0" }, name: "A" }, null, 2);
    const out = JSON.parse(withMod(text, { name: "New", hash: "0123456789abcdef", link: "https://example.org" }));
    expect(Object.keys(out)).toEqual(["key", "mod", "name"]);
    expect(out.mod).toEqual({ name: "New", hash: "0123456789abcdef", link: "https://example.org" });
  });
});
